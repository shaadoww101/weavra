let agents = [], knowledge = [], workflows = [], selectedAgent = 'Atlas', currentRun = null;

async function api(path, opts) {
  const r = await fetch(path, { headers: { 'Content-Type': 'application/json' }, ...(opts || {}) });
  if (!r.ok) throw new Error((await r.json().catch(() => ({}))).error || r.statusText);
  return r.json();
}
function esc(s) { return String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c])); }
function toast(m) { const t = document.getElementById('toast'); t.textContent = m; t.classList.add('show'); setTimeout(() => t.classList.remove('show'), 3000); }

async function init() {
  try {
    const health = await api('/api/health');
    const pill = document.getElementById('modepill');
    pill.textContent = health.mode === 'live' ? `● LIVE AI (${esc(health.provider)})` : '● DEMO MODE — no LLM key set';
    pill.classList.toggle('live', health.mode === 'live');
    document.getElementById('modenote').textContent = health.mode === 'live'
      ? 'Live mode: chat answers are generated by the configured LLM, grounded in the knowledge base below.'
      : 'Demo mode: no LLM key is set, so chat answers are built from the seeded knowledge base and are clearly labelled DEMO. Set LLM_PROVIDER + a key (see README) for live AI.';
  } catch (e) { document.getElementById('modepill').textContent = '● API OFFLINE'; }
  agents = await api('/api/agents').catch(() => []);
  knowledge = await api('/api/knowledge').catch(() => []);
  workflows = await api('/api/workflows').catch(() => []);
  renderAgents(); renderPicker(); renderKnowledge(); renderWorkflows(); renderTemplates();
}
function renderAgents() {
  document.getElementById('agentgrid').innerHTML = agents.map(a => `
    <article class="agent"><div style="display:flex;justify-content:space-between;align-items:center">
      <div class="avatar" style="background:${a.color}">${esc(a.initial)}</div><span style="color:var(--lime);font:10px 'DM Mono',monospace">● AVAILABLE</span></div>
      <h3>${esc(a.name)}</h3><div class="role">${esc(a.role).toUpperCase()}</div><p>${esc(a.description)}</p>
      <div style="display:flex;gap:6px;flex-wrap:wrap"><span class="chip">${esc(a.category)}</span>${(a.tools || []).slice(0, 2).map(t => `<span class="chip">${esc(t)}</span>`).join('')}</div>
      <div class="agentfoot"><span class="mono" style="font-size:11px">${esc(a.price)}</span>
      <button class="btn small" onclick="showAgent('${esc(a.id)}')">Meet ${esc(a.name)} ↗</button></div></article>`).join('');
}
function showAgent(id) {
  const a = agents.find(x => x.id === id); if (!a) return;
  const docs = knowledge.filter(d => d.collection.toLowerCase().startsWith(a.name.toLowerCase()));
  document.getElementById('modalTitle').textContent = a.name;
  document.getElementById('modalRole').textContent = a.role.toUpperCase() + ' · ' + a.price;
  document.getElementById('modalText').textContent = a.description + ' ' + a.instructions;
  document.getElementById('modalKb').innerHTML = docs.length ? docs.map(d => `<div class="kbitem"><b>${esc(d.title)}</b><small>${esc(d.content)}</small></div>`).join('') : '<p style="color:var(--muted);font-size:12px">Uses the shared knowledge base.</p>';
  document.getElementById('modalChat').onclick = () => { closeAgent(); selectAgent(a.name); document.getElementById('chat').scrollIntoView({ behavior: 'smooth' }); };
  document.getElementById('agentModal').classList.add('open');
}
function closeAgent() { document.getElementById('agentModal').classList.remove('open'); }
function renderPicker() {
  document.getElementById('picker').innerHTML = agents.map(a => `<button class="pick ${a.name === selectedAgent ? 'active' : ''}" onclick="selectAgent('${esc(a.name)}')">${esc(a.name)}</button>`).join('');
}
function selectAgent(name) { selectedAgent = name; renderPicker(); renderKnowledge(); document.getElementById('chatAgentLabel').textContent = name; }
function renderKnowledge() {
  const list = knowledge.filter(d => !selectedAgent || d.collection.toLowerCase().startsWith(selectedAgent.toLowerCase()) || ['Company handbook', 'Product documentation', 'Sales playbook'].includes(d.collection));
  const show = list.length ? list : knowledge;
  document.getElementById('kblist').innerHTML = show.map(d => `<div class="kbitem"><b>${esc(d.title)}</b><small>${esc(d.collection)} — ${esc(d.content.slice(0, 180))}${d.content.length > 180 ? '…' : ''}</small></div>`).join('');
  document.getElementById('kbcount').textContent = knowledge.length + ' DOCS';
}
async function sendChat() {
  const inp = document.getElementById('chatInput'); const q = inp.value.trim(); if (!q) return;
  const box = document.getElementById('chatMsgs');
  box.insertAdjacentHTML('beforeend', `<div class="bubble user">${esc(q)}</div>`);
  inp.value = ''; box.scrollTop = box.scrollHeight;
  try {
    const res = await api('/api/chat', { method: 'POST', body: JSON.stringify({ agent: selectedAgent, message: q }) });
    const cites = (res.citations || []).map(c => esc(c.title)).join(' · ');
    box.insertAdjacentHTML('beforeend', `<div class="bubble ai"><b style="color:var(--lime)">${esc(res.agent)} · ${esc(res.mode.toUpperCase())}</b><br>${esc(res.answer)}${cites ? `<span class="src">SOURCE: ${cites}</span>` : '<span class="src">SOURCE: No matching source · abstention</span>'}</div>`);
  } catch (e) { box.insertAdjacentHTML('beforeend', `<div class="bubble ai">Error: ${esc(e.message)}</div>`); }
  box.scrollTop = box.scrollHeight;
}
async function addKnowledge() {
  const title = document.getElementById('kbTitle').value.trim(), coll = document.getElementById('kbCollection').value.trim(), content = document.getElementById('kbContent').value.trim();
  if (!title || !coll || !content) return toast('Fill in title, collection and content first.');
  await api('/api/knowledge', { method: 'POST', body: JSON.stringify({ title, collection: coll, content }) });
  knowledge = await api('/api/knowledge'); renderKnowledge(); toast('Knowledge added.');
  document.getElementById('kbTitle').value = ''; document.getElementById('kbContent').value = '';
}
function renderWorkflows() {
  document.getElementById('wflist').innerHTML = workflows.map(w => `
    <div class="card" style="margin-bottom:12px"><div style="display:flex;justify-content:space-between;align-items:center;gap:10px;flex-wrap:wrap">
    <div><b>${esc(w.name)}</b><div style="color:var(--muted);font-size:12px">${w.steps.map(s => esc(s.title)).join(' → ')}</div></div>
    <button class="btn small primary" onclick="runWorkflow('${esc(w.id)}')">▶ Run</button></div></div>`).join('');
}
const TEMPLATES = {
  'Product launch plan': [['Trigger', 'Launch brief received', ''], ['Agent', 'Atlas researches market', 'Atlas'], ['Agent', 'Signal finds audience insights', 'Signal'], ['Agent', 'Quill writes launch messaging', 'Quill'], ['Agent', 'Pulse plans growth experiments', 'Pulse'], ['Approval', 'Approve launch plan', ''], ['Output', 'Deliver launch plan', '']],
  'Customer support triage': [['Trigger', 'New support request', ''], ['Knowledge', 'Check support knowledge', ''], ['Agent', 'Relay triages the request', 'Relay'], ['Approval', 'Approve response', ''], ['Output', 'Send response', '']],
  'Content campaign': [['Trigger', 'Campaign brief received', ''], ['Agent', 'Quill plans campaign', 'Quill'], ['Agent', 'Pulse plans distribution', 'Pulse'], ['Approval', 'Approve campaign', ''], ['Output', 'Publish campaign', '']],
  'Research brief': [['Trigger', 'Research question received', ''], ['Agent', 'Atlas researches the question', 'Atlas'], ['Agent', 'Signal analyses the data', 'Signal'], ['Approval', 'Approve brief', ''], ['Output', 'Deliver brief', '']],
};
function renderTemplates() {
  document.getElementById('templates').innerHTML = Object.keys(TEMPLATES).map(t => `<button class="pick" onclick="loadTemplate('${esc(t)}')">${esc(t)}</button>`).join('') + `<button class="pick" onclick="loadTemplate('')">Blank</button>`;
}
let builderSteps = [];
function loadTemplate(name) {
  builderSteps = (TEMPLATES[name] || []).map(([type, title, agent]) => ({ type, title, desc: title, agent }));
  if (!name) builderSteps = [{ type: 'Trigger', title: 'New request', desc: 'A new request starts the workflow', agent: '' }];
  renderBuilder();
}
function renderBuilder() {
  document.getElementById('builderSteps').innerHTML = builderSteps.map((s, i) => `
    <div class="step"><select onchange="builderSteps[${i}].type=this.value">
      ${['Trigger', 'Knowledge', 'Agent', 'Approval', 'Output'].map(t => `<option ${s.type === t ? 'selected' : ''}>${t}</option>`).join('')}</select>
    <input value="${esc(s.title)}" onchange="builderSteps[${i}].title=this.value" placeholder="Step title">
    <select onchange="builderSteps[${i}].agent=this.value"><option value="">—</option>${agents.map(a => `<option ${s.agent === a.name ? 'selected' : ''}>${a.name}</option>`).join('')}</select>
    <button class="btn small" onclick="builderSteps.splice(${i},1);renderBuilder()">×</button></div>`).join('') || '<p style="color:var(--muted)">No steps yet — load a template or add one.</p>';
}
function addStep() { builderSteps.push({ type: 'Agent', title: 'New agent step', desc: 'Agent processes the task', agent: selectedAgent }); renderBuilder(); }
async function saveWorkflow() {
  const name = document.getElementById('wfName').value.trim() || 'My workflow';
  if (!builderSteps.length) return toast('Add at least one step first.');
  const wf = await api('/api/workflows', { method: 'POST', body: JSON.stringify({ name, steps: builderSteps }) });
  workflows = await api('/api/workflows'); renderWorkflows(); toast(`Saved "${wf.name}".`);
}
async function runWorkflow(id) {
  const log = document.getElementById('wflog');
  log.textContent = '[SYSTEM] Starting workflow…';
  const run = await api(`/api/workflows/${id}/run`, { method: 'POST', body: '{}' });
  currentRun = run;
  log.textContent = run.log.join('\n') + (run.results.length ? '\n\n--- Results ---\n' + run.results.map(r => `[${r.step}] ${r.title}: ${(r.output || '').slice(0, 300)}`).join('\n\n') : '');
  document.getElementById('approveBtn').style.display = run.status === 'waiting_approval' ? '' : 'none';
  if (run.status === 'waiting_approval') toast('Paused at human approval — click Approve to continue.');
}
async function approveRun() {
  if (!currentRun) return;
  const run = await api(`/api/workflows/${currentRun.workflowId}/approve`, { method: 'POST', body: JSON.stringify({ runId: currentRun.id }) });
  currentRun = run;
  document.getElementById('wflog').textContent = run.log.join('\n') + (run.results.length ? '\n\n--- Results ---\n' + run.results.map(r => `[${r.step}] ${r.title}: ${(r.output || '').slice(0, 300)}`).join('\n\n') : '');
  document.getElementById('approveBtn').style.display = run.status === 'waiting_approval' ? '' : 'none';
}
async function joinWaitlist(e) {
  e.preventDefault();
  const name = document.getElementById('wlName').value.trim(), email = document.getElementById('wlEmail').value.trim(), type = document.getElementById('wlType').value;
  await api('/api/waitlist', { method: 'POST', body: JSON.stringify({ name, email, type }) });
  toast('Thanks — you are on the list.'); e.target.reset();
}
